"""Second pass: is the candidate actually a vertical slide?

Frame difference answers "did the picture change a lot", and the corpus
shows that is the wrong question -- a hard cut inside a video changes the
picture more than a swipe does. A scroll has a property a cut does not: the
whole frame travels upward by about one screen height. Nothing else in a
feed does that.

Phase correlation gives that translation per frame pair. Summing the
vertical component across a candidate's frames gives the distance the
picture travelled, in screen heights, and that is what separates the two.

Caveat worth keeping in view: the corpus slides are generated by ffmpeg's
xfade, so they are geometrically perfect translations. A real swipe carries
a moving subject inside the sliding frame, the incoming video is already
playing, and phones add rubber-banding at the ends. Expect this number to
be better here than it would be on a real recording.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import cv2
import numpy as np

from detect import read_frames

WIDTH = 64


@dataclass
class Candidate:
    time: float
    peak_diff: float
    travel: float  # vertical distance travelled, in screen heights
    coherence: float  # share of the run's frames moving the same way


def measure(path: Path, times: list[float], window: float = 0.45) -> list[Candidate]:
    """For each candidate time, how far did the picture slide vertically."""
    _, frames, stamps = read_frames(path, WIDTH)
    if not frames:
        return []
    height = frames[0].shape[0]
    hann = cv2.createHanningWindow((frames[0].shape[1], height), cv2.CV_32F)

    out = []
    for t in times:
        # Found by timestamp rather than t * fps: under a variable frame
        # rate those are not the same frame, and the window would slide off
        # the swipe it is supposed to be centred on.
        lo = max(1, int(np.searchsorted(stamps, t - window, side="left")))
        hi = min(len(frames) - 1, int(np.searchsorted(stamps, t + window, side="right")) - 1)
        shifts = []
        diffs = []
        for i in range(lo, hi + 1):
            (_, dy), _ = cv2.phaseCorrelate(frames[i - 1], frames[i], hann)
            shifts.append(dy)
            diffs.append(float(np.mean(np.abs(frames[i] - frames[i - 1]))))
        if not shifts:
            out.append(Candidate(t, 0.0, 0.0, 0.0))
            continue

        arr = np.asarray(shifts)
        # A scroll moves one way for the whole swipe. Sum only the frames
        # going in the dominant direction: summing the raw signed values
        # would let a jitter in the other direction cancel real travel out.
        dominant = np.sign(np.sum(arr))
        same = arr[np.sign(arr) == dominant]
        travel = float(np.abs(same).sum() / height)
        coherence = float(len(same) / len(arr))
        out.append(Candidate(t, max(diffs), travel, coherence))
    return out
