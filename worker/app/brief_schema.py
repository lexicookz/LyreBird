"""Adapt contract: what goes into brief generation and what comes out.

This module is the single source of truth for the brief shape. Three things
read it:

- the Adapt endpoint passes BriefDraft to Gemini as `response_schema` and
  validates the reply with it before anything is written to `briefs.payload`
- worker/schemas/*.schema.json are exported from it (run this module), and
- types/brief.ts mirrors those files by hand for the app and the mock data,
  with __tests__/briefSchema.test.ts failing if the two drift.

Change a field here, re-export, and update types/brief.ts in the same commit.

Adapt is text only. Its input is a stored analysis payload plus a
BrandProfile; video is never re-sent to Gemini.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.models import Brand, CalendarPlatform

# Mirrors FunnelStage in types/index.ts and pipeline/schema.py.
FunnelStage = Literal["TOFU", "MOFU", "BOFU"]

# Top-level keys of an analyses.payload (AnalysisPayload in types/index.ts).
# why_it_works points back at one of these, so every adapted element can be
# traced to what the source video actually did.
AnalysisField = Literal[
    "hook",
    "transcript",
    "onScreenText",
    "shotBeats",
    "pacing",
    "cta",
    "format",
    "funnelStage",
]


class _Input(BaseModel):
    """What we hand the model. Unknown keys here mean our own code is wrong,
    so they fail loudly."""

    model_config = ConfigDict(extra="forbid")


class _Output(BaseModel):
    """What the model hands back.

    Deliberately NOT extra="forbid". Pydantic turns that into
    `additionalProperties: false`, which the SDK sends as
    `additional_properties` and Gemini rejects outright -- every brief call
    died with "Cannot find field" before the model ran.

    Little is lost. These classes are passed as `response_schema`, so
    generation is constrained to exactly these fields; an unknown key is not
    something the model is able to produce. The strictness was guarding
    against a case the schema already prevents, at the cost of the request
    being rejected.
    """

    model_config = ConfigDict(extra="ignore")


# ---------- input ----------


class BrandProfile(_Input):
    """What Adapt knows about who the brief is for. Built from a brands row."""

    name: str
    niche: str = Field(description="The niche, person or brand the content is about.")
    target_audience: str
    tone: str
    goal: str = Field(description="What the content should get viewers to do.")
    constraints: list[str] = Field(
        default=[], description="Words and claims the brief must avoid."
    )
    style_profile: dict[str, Any] | None = None

    @classmethod
    def from_brand(cls, brand: Brand) -> BrandProfile:
        """Maps a brands row onto the profile Adapt reads.

        niche falls back to product_summary because the app only writes the
        latter today. Missing text becomes "" rather than failing: a sparse
        profile still produces a usable brief, just a less tailored one.
        """
        return cls(
            name=brand.name,
            niche=brand.niche or brand.product_summary or "",
            target_audience=brand.target_audience or "",
            tone=brand.tone_of_voice or "",
            goal=brand.goal or "",
            constraints=brand.constraints,
            style_profile=brand.style_profile,
        )


# ---------- output ----------
# Everything below is generated by the model. Fields the server already knows
# (analysis_id, brand_id, prompt_version, model_version, created_at) live in
# their own briefs columns, so the model is never asked to repeat them.


class Hook(_Output):
    line: str = Field(description="The spoken opening line.")
    on_screen_text: str = Field(description='Text overlay for the hook, or "" for none.')
    visual: str = Field(description="What is on screen in the first seconds.")


class Beat(_Output):
    start_seconds: float = Field(ge=0)
    # ge rather than gt. Pydantic turns gt into exclusiveMinimum, which
    # Gemini's response_schema rejects outright -- "Extra inputs are not
    # permitted" -- so every brief call failed with a 422 before the model
    # ran. The beat still cannot end at zero: _ends_after_start below
    # requires end > start, and start is ge=0.
    end_seconds: float = Field(ge=0)
    shot: str = Field(description="Framing and subject, e.g. 'Overhead, hands on grinder'.")
    action: str = Field(description="What happens in the shot.")
    voiceover: str = Field(description='Spoken words over this beat, or "".')
    on_screen_text: str = Field(description='Text overlay for this beat, or "".')

    @model_validator(mode="after")
    def _ends_after_start(self) -> Beat:
        if self.end_seconds <= self.start_seconds:
            raise ValueError("end_seconds must be after start_seconds")
        return self


class WhyItWorks(_Output):
    brief_element: str = Field(description="Which part of this brief, e.g. 'hook' or 'beat 3'.")
    source_field: AnalysisField = Field(description="The analysis field it was adapted from.")
    source_detail: str = Field(description="What the source video did there.")
    rationale: str = Field(description="Why carrying it over should work for this brand.")


class PostingSlot(_Output):
    """A relative slot. Dates are computed in code from day_offset, because
    models are unreliable at date arithmetic."""

    day_offset: int = Field(ge=0, le=13, description="Days after the brief is created.")
    start_hour: int = Field(ge=0, le=23, description="Local time, 24h.")
    end_hour: int = Field(ge=1, le=24, description="Local time, 24h, exclusive.")
    platform: CalendarPlatform
    rationale: str

    @model_validator(mode="after")
    def _window_is_forward(self) -> PostingSlot:
        if self.end_hour <= self.start_hour:
            raise ValueError("end_hour must be after start_hour")
        return self


class BriefDraft(_Output):
    """Gemini's structured output for one Adapt run. Stored as briefs.payload."""

    title: str
    funnel_stage: FunnelStage
    # ge=1, not gt=0, for the same reason as Beat.end_seconds. Identical
    # meaning for an integer, and it emits `minimum`, which Gemini accepts.
    target_duration_seconds: int = Field(ge=1, le=180)
    hook: Hook
    beats: list[Beat] = Field(min_length=1)
    cta: str
    caption: str
    hashtags: list[str]
    why_it_works: list[WhyItWorks] = Field(min_length=1)
    production_notes: list[str]
    posting_slots: list[PostingSlot] = Field(min_length=1, max_length=3)

    @model_validator(mode="after")
    def _beats_in_order(self) -> BriefDraft:
        for prev, cur in zip(self.beats, self.beats[1:]):
            if cur.start_seconds < prev.end_seconds:
                raise ValueError("beats must be in order and must not overlap")
        return self


# ---------- briefs row ----------


def _seconds(value: float) -> str:
    return f"{value:g}"


def to_brief_columns(
    draft: BriefDraft, *, prompt_version: str, model_version: str
) -> dict[str, Any]:
    """The briefs columns a generated draft fills, ready to spread into an insert.

    payload keeps the draft exactly as generated. The flat columns are the
    editable copy the screens read, so they are flattened to what the app
    expects: shot_list must stay a list of plain strings, because shotsOf() in
    data/briefs.ts drops anything that isn't one.

    The versions are required here because briefs_payload_traceable rejects a
    payload without them.
    """
    return {
        "hook": draft.hook.line,
        "script": " ".join(b.voiceover for b in draft.beats if b.voiceover.strip()),
        "shot_list": [
            f"{_seconds(b.start_seconds)}-{_seconds(b.end_seconds)}s  {b.shot}"
            for b in draft.beats
        ],
        "caption": draft.caption,
        "cta": draft.cta,
        # Stored without the '#', matching the seed data and mock briefs.
        "hashtags": [tag.lstrip("#") for tag in draft.hashtags if tag.lstrip("#")],
        "payload": draft.model_dump(mode="json"),
        "prompt_version": prompt_version,
        "model_version": model_version,
    }


# ---------- export ----------

SCHEMA_DIR = Path(__file__).resolve().parent.parent / "schemas"
EXPORTS = {
    "brand_profile.schema.json": BrandProfile,
    "brief_draft.schema.json": BriefDraft,
}


def export_schemas() -> None:
    SCHEMA_DIR.mkdir(exist_ok=True)
    for filename, model in EXPORTS.items():
        text = json.dumps(model.model_json_schema(), indent=2, sort_keys=True)
        (SCHEMA_DIR / filename).write_text(text + "\n", encoding="utf-8")


if __name__ == "__main__":
    export_schemas()
